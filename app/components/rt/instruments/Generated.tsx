import { InlineExtensionFrame } from "@agent-native/toolkit/app/extensions";
import { useMemo } from "react";

import type { InstrumentRow } from "@shared/investigation";

import type { Workspace } from "../lib";

/**
 * A generated instrument is a sandboxed extension mounted with the instrument
 * as its slot context. It reads bound evidence from `slotContext` and writes
 * back only through actions (adjust-instrument, record-artifacts), so the
 * same validation and impact tracking apply as for native instruments.
 */
export function GeneratedInstrument({ ws, instrument }: { ws: Workspace; instrument: InstrumentRow }) {
  const context = useMemo(() => {
    const boundArtifacts = new Set(instrument.boundArtifactIds);
    const boundSources = new Set(instrument.boundSourceIds);
    return {
      investigationId: ws.investigation.id,
      instrument: {
        id: instrument.id,
        code: instrument.code,
        title: instrument.title,
        question: instrument.question,
        params: instrument.params,
        userState: instrument.userState,
        version: instrument.version,
      },
      artifacts: ws.artifacts
        .filter((a) => boundArtifacts.has(a.id))
        .map((a) => ({ id: a.id, code: a.code, type: a.type, label: a.label, status: a.status, epistemic: a.epistemic, attrs: a.attrs, citations: a.citations })),
      sources: ws.sources
        .filter((s) => boundSources.has(s.id))
        .map((s) => ({ id: s.id, code: s.code, kind: s.kind, title: s.title, content: s.kind === "image" ? null : s.content })),
      links: ws.links.filter((l) => boundArtifacts.has(l.fromId) || boundArtifacts.has(l.toId)).map((l) => ({ id: l.id, code: l.code, fromId: l.fromId, toId: l.toId, relation: l.relation, status: l.status })),
      assumptions: ws.assumptions.filter((a) => a.active).map((a) => ({ id: a.id, code: a.code, kind: a.kind, label: a.label, value: a.value })),
    };
  }, [ws, instrument]);

  if (!instrument.extensionId) {
    return <div className="p-8 text-sm text-muted-foreground">This generated instrument has no extension attached.</div>;
  }
  return (
    <div className="px-5 py-4">
      <InlineExtensionFrame extensionId={instrument.extensionId} slotId="redthread.instrument" context={context} initialHeight={520} className="w-full" />
      <p className="mt-2 text-[11px] text-muted-foreground">
        Generated by the co-investigator for this question. Runs sandboxed; changes go through the same validated actions as native instruments.
      </p>
    </div>
  );
}
